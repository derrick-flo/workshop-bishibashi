function glyphOf(font: Font, char: string): Glyph {
	return font.glyphs[char] ?? font.glyphs["?"] ?? [];
}

export function textWidth(font: Font, value: string): number {
	const chars = [...value];
	const widths = chars.map((char) => glyphOf(font, char)[0]?.length ?? 0);
	return widths.reduce((sum, w) => sum + w, 0) + Math.max(0, chars.length - 1) * font.spacing;
}

/** 글자를 그림으로. 모르는 글자는 '?'로 그린다. */
export function text(font: Font, value: string, color: number): Bitmap {
	const result = blank(textWidth(font, value), font.height);
	let cursor = 0;
	for (const char of value) {
		const glyph = glyphOf(font, char);
		glyph.forEach((row, y) => {
			[...row].forEach((cell, x) => {
				if (cell === "#") result.px[y * result.w + cursor + x] = color;
			});
		});
		cursor += (glyph[0]?.length ?? 0) + font.spacing;
	}
	return result;
}

/** 외곽선을 두른 글자(배경 위에서도 잘 보이게) */
export function label(font: Font, value: string, color: number, edge: number): Bitmap {
	return edge === CLEAR ? text(font, value, color) : outline(text(font, value, color), edge);
}
